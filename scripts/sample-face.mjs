// Build step (runs before `npm run build`): converts ../atom-face.png into
// branding/generated/face-data.ts. The reference is cropped to its artwork,
// area-averaged in linear light onto a fixed grid and stored as palette
// indices. The PNG itself is never read at runtime.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";
import { decodePng } from "./png.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(root, "atom-face.png");
const OUTPUT = join(root, "branding/generated/face-data.ts");
const SCALE = 2; // one grid pixel averages SCALE x SCALE source pixels
const PADDING = 8; // source pixels kept around the bounding box of the artwork
const BACKGROUND = 16; // channel values at or below this are empty background
const PALETTE_SIZE = 256;
// The solid ATOM lettering in source pixels; narrow terminals swap it for a caption.
const WORDMARK = { x: 490, y: 452, width: 800, height: 198 };

const toLinear = Array.from({ length: 256 }, (_, v) => { const c = v / 255; return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; });
const toSrgb = l => Math.round(255 * Math.max(0, Math.min(1, l <= 0.0031308 ? l * 12.92 : 1.055 * l ** (1 / 2.4) - 0.055)));

const png = decodePng(readFileSync(SOURCE));

// Crop to the artwork so terminal columns are spent on the dragon, not margins.
let x0 = png.width, y0 = png.height, x1 = -1, y1 = -1;
for (let y = 0; y < png.height; y++) for (let x = 0; x < png.width; x++) {
	if (Math.max(...png.rgb(x, y)) > BACKGROUND) {
		if (x < x0) x0 = x;
		if (x > x1) x1 = x;
		if (y < y0) y0 = y;
		if (y > y1) y1 = y;
	}
}
if (x1 < 0) throw new Error("atom-face.png is entirely background");
const crop = { x: Math.max(0, x0 - PADDING), y: Math.max(0, y0 - PADDING) };
crop.width = Math.min(png.width - crop.x, Math.ceil((x1 + PADDING + 1 - crop.x) / SCALE) * SCALE);
crop.height = Math.min(png.height - crop.y, Math.ceil((y1 + PADDING + 1 - crop.y) / SCALE) * SCALE);
const width = Math.ceil(crop.width / SCALE), height = Math.ceil(crop.height / SCALE);

// Box-filter in linear light, then quantize the sRGB result with median cut.
const colors = [];
for (let gy = 0; gy < height; gy++) for (let gx = 0; gx < width; gx++) {
	let r = 0, g = 0, b = 0, n = 0;
	for (let y = crop.y + gy * SCALE; y < Math.min(crop.y + crop.height, crop.y + (gy + 1) * SCALE); y++) {
		for (let x = crop.x + gx * SCALE; x < Math.min(crop.x + crop.width, crop.x + (gx + 1) * SCALE); x++) {
			const [sr, sg, sb] = png.rgb(x, y);
			r += toLinear[sr]; g += toLinear[sg]; b += toLinear[sb]; n++;
		}
	}
	colors.push([toSrgb(r / n), toSrgb(g / n), toSrgb(b / n)]);
}
const boxes = [colors.slice()];
while (boxes.length < PALETTE_SIZE) {
	let widest = -1, range = 0, axis = 0;
	boxes.forEach((box, i) => {
		if (box.length < 2) return;
		for (let channel = 0; channel < 3; channel++) {
			let low = 255, high = 0;
			for (const color of box) {
				if (color[channel] < low) low = color[channel];
				if (color[channel] > high) high = color[channel];
			}
			if (high - low > range) { range = high - low; widest = i; axis = channel; }
		}
	});
	if (widest < 0) break;
	const box = boxes[widest].sort((a, b) => a[axis] - b[axis]);
	boxes.splice(widest, 1, box.slice(0, box.length >> 1), box.slice(box.length >> 1));
}
const palette = boxes.map(box => box.reduce((sum, c) => [sum[0] + c[0], sum[1] + c[1], sum[2] + c[2]], [0, 0, 0]).map(v => Math.round(v / box.length)));
const indices = new Uint8Array(colors.length);
let error = 0;
colors.forEach((color, i) => {
	let best = 0, distance = Infinity;
	palette.forEach((entry, p) => {
		const d = (entry[0] - color[0]) ** 2 + (entry[1] - color[1]) ** 2 + (entry[2] - color[2]) ** 2;
		if (d < distance) { distance = d; best = p; }
	});
	indices[i] = best;
	error += distance;
});

const grid = v => Math.round(v / SCALE);
const wordmark = { x: grid(WORDMARK.x - crop.x), y: grid(WORDMARK.y - crop.y), width: grid(WORDMARK.width), height: grid(WORDMARK.height) };
const pixels = deflateSync(indices, { level: 9 }).toString("base64").match(/.{1,120}/g);
const hex = palette.map(c => c.map(v => v.toString(16).padStart(2, "0")).join("")).join("");
mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT, `// Generated by scripts/sample-face.mjs from atom-face.png (${png.width}x${png.height}). Do not edit.
export const FACE_WIDTH = ${width};
export const FACE_HEIGHT = ${height};
/** The part of the reference the grid covers, in source pixels. */
export const FACE_SOURCE = { x: ${crop.x}, y: ${crop.y}, width: ${crop.width}, height: ${crop.height}, scale: ${SCALE} } as const;
/** The solid ATOM lettering, in grid pixels. */
export const WORDMARK_BOX = { x: ${wordmark.x}, y: ${wordmark.y}, width: ${wordmark.width}, height: ${wordmark.height} } as const;
/** ${palette.length} sRGB colors, six hex digits each. */
export const FACE_PALETTE = "${hex}";
/** FACE_WIDTH x FACE_HEIGHT palette indices, row-major, deflated, base64. */
export const FACE_PIXELS = [
${pixels.map(line => `\t"${line}",`).join("\n")}
].join("");
`);
console.log(`atom-face.png ${png.width}x${png.height} -> crop ${crop.width}x${crop.height} at (${crop.x}, ${crop.y}) -> ${width}x${height} grid, ${palette.length} colors (rms error ${Math.sqrt(error / colors.length).toFixed(2)}), ${pixels.join("").length} base64 bytes`);
